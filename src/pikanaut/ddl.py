"""DDL: CREATE TABLE / CREATE INDEX / DROP TABLE из модели (SPEC.md, раздел 11).

Рендер свой, не pypika: у неё `create_index` не квотирует идентификаторы, нет диалектного
DDL (identity, типы) и нет column-level ограничений.

Правила: значения берутся из модели, всё остальное — из меток `Col`. Незнакомый тип не
превращается в TEXT молча, а падает `SchemaError` с подсказкой про `Col(type=...)`.
"""

from __future__ import annotations

import hashlib
import warnings
from datetime import date, datetime, time
from decimal import Decimal
from enum import Enum
from typing import Any, get_args, get_origin
from uuid import UUID

from .build import Sql
from .dialects.base import Dialect, Feature
from .errors import SchemaError, UnsupportedFeature
from .schema import UNSET, Field, M, TableInfo, table_of

MAX_IDENTIFIER = 63          # предел Postgres; SQLite длину не ограничивает


class _Now:
    """Маркер «дефолт ставит база»: `Col(default=NOW)` → CURRENT_TIMESTAMP."""

    __slots__ = ()

    def __repr__(self) -> str:
        return "NOW"


NOW = _Now()

# kind → (SQLite, Postgres)
_TYPES: dict[str, tuple[str, str]] = {
    "bool": ("INTEGER", "BOOLEAN"),
    "int": ("INTEGER", "INTEGER"),
    "float": ("REAL", "DOUBLE PRECISION"),
    "str": ("TEXT", "TEXT"),
    "bytes": ("BLOB", "BYTEA"),
    "datetime": ("TEXT", "TIMESTAMPTZ"),
    "date": ("TEXT", "DATE"),
    "time": ("TEXT", "TIME"),
    "uuid": ("TEXT", "UUID"),
    "decimal": ("TEXT", "NUMERIC"),     # TEXT — чтобы не потерять точность (SPEC.md, 11)
    "json": ("TEXT", "JSONB"),
    "enum": ("TEXT", "TEXT"),
}


def create(
    model: type[M],
    *,
    dialect: Dialect,
    if_not_exists: bool = True,
) -> list[Sql]:
    """CREATE TABLE (+ CREATE INDEX) для модели. Один statement на элемент списка."""
    info = table_of(model)
    _require_dialect_support(info, dialect)

    columns = ",".join(_column_sql(field, dialect) for field in info.fields)
    constraints = _constraints_sql(info, dialect)
    body = f"{columns},{constraints}" if constraints else columns

    prefix = "CREATE TABLE IF NOT EXISTS " if if_not_exists else "CREATE TABLE "
    statements = [Sql(f"{prefix}{_table_sql(info, dialect)} ({body})", [], dialect)]

    index_prefix = "CREATE INDEX IF NOT EXISTS " if if_not_exists else "CREATE INDEX "
    for field in info.fields:
        if field.index:
            statements.append(
                Sql(
                    f"{index_prefix}{_quote(_name('ix', info.name, field.column), dialect)} "
                    f"ON {_table_sql(info, dialect)} ({_quote(field.column, dialect)})",
                    [],
                    dialect,
                )
            )
    return statements


def drop(model: type[M], *, dialect: Dialect, if_exists: bool = True) -> Sql:
    """DROP TABLE для модели."""
    info = table_of(model)
    _require_dialect_support(info, dialect)
    prefix = "DROP TABLE IF EXISTS " if if_exists else "DROP TABLE "
    return Sql(f"{prefix}{_table_sql(info, dialect)}", [], dialect)


# --- рендер частей ---------------------------------------------------------


def _quote(identifier: str, dialect: Dialect) -> str:
    quote = dialect.quote_char
    return f"{quote}{identifier}{quote}"


def _table_sql(info: TableInfo, dialect: Dialect) -> str:
    name = _quote(info.name, dialect)
    if info.schema:
        return f"{_quote(info.schema, dialect)}.{name}"
    return name


def _require_dialect_support(info: TableInfo, dialect: Dialect) -> None:
    if info.schema and not dialect.has(Feature.SCHEMA):
        raise UnsupportedFeature(
            dialect.name,
            "schema",
            "drop @table(schema=...) or use a dialect that supports schemas",
        )


def _column_sql(field: Field, dialect: Dialect) -> str:
    parts = [_quote(field.column, dialect), _sql_type(field, dialect)]
    if _inline_primary_key(field, dialect):
        parts.append("PRIMARY KEY")
    elif not field.nullable:
        parts.append("NOT NULL")
    if field.default is not UNSET:
        parts.append(f"DEFAULT {_default_sql(field.default, dialect)}")
    return " ".join(parts)


def _sql_type(field: Field, dialect: Dialect) -> str:
    if field.sql_type is not None:
        return field.sql_type
    if _identity(field, dialect):
        if _family(dialect) == "sqlite":
            return "INTEGER"
        return "INTEGER GENERATED BY DEFAULT AS IDENTITY"

    kind = _kind(field.annotation)
    if kind not in _TYPES:
        raise SchemaError(
            f"{field.name}: no SQL type for {field.annotation!r} — "
            'set it explicitly with Col(type="..."): nested models and arbitrary classes '
            "have no portable mapping"
        )
    sqlite_type, postgres_type = _TYPES[kind]
    return sqlite_type if _family(dialect) == "sqlite" else postgres_type


def _family(dialect: Dialect) -> str:
    return "sqlite" if dialect.name.startswith("sqlite") else "postgres"


def _non_optional(annotation: Any) -> Any:
    """`int | None` → `int`; всё остальное без изменений."""
    args = get_args(annotation)
    if args and type(None) in args:
        rest = [arg for arg in args if arg is not type(None)]
        if len(rest) == 1:
            return rest[0]
    return annotation


def _identity(field: Field, dialect: Dialect) -> bool:
    """Суррогатный ключ: pk + nullable + int — значит значение выдаёт база."""
    return (
        field.pk
        and field.nullable
        and _non_optional(field.annotation) is int
        and field.sql_type is None
    )


def _inline_primary_key(field: Field, dialect: Dialect) -> bool:
    """SQLite требует `INTEGER PRIMARY KEY` в описании колонки, иначе rowid-алиаса нет."""
    return _identity(field, dialect) and _family(dialect) == "sqlite"


def _constraints_sql(info: TableInfo, dialect: Dialect) -> str:
    parts: list[str] = []

    pk_fields = [field for field in info.fields if field.pk]
    inline_pk = len(pk_fields) == 1 and _inline_primary_key(pk_fields[0], dialect)
    if pk_fields and not inline_pk:
        columns = ",".join(_quote(field.column, dialect) for field in pk_fields)
        parts.append(
            f"CONSTRAINT {_quote(_name('pk', info.name), dialect)} PRIMARY KEY ({columns})"
        )

    for field in info.fields:
        if field.unique:
            parts.append(
                f"CONSTRAINT {_quote(_name('uq', info.name, field.column), dialect)} "
                f"UNIQUE ({_quote(field.column, dialect)})"
            )
    return ",".join(parts)


def _kind(annotation: Any) -> str:
    annotation = _non_optional(annotation)
    origin = get_origin(annotation)
    if origin is not None:
        return "json" if origin in (dict, list, tuple) else "unknown"
    if isinstance(annotation, type):
        if issubclass(annotation, Enum):
            return "enum"
        for known, kind in (
            (bool, "bool"),
            (int, "int"),
            (float, "float"),
            (str, "str"),
            (bytes, "bytes"),
            (datetime, "datetime"),
            (date, "date"),
            (time, "time"),
            (UUID, "uuid"),
            (Decimal, "decimal"),
        ):
            if annotation is known:
                return kind
    return "unknown"


def _default_sql(value: Any, dialect: Dialect) -> str:
    if value is NOW:
        return "CURRENT_TIMESTAMP"
    if value is None:
        return "NULL"
    if isinstance(value, Enum):
        value = value.value
    if isinstance(value, bool):
        if _family(dialect) == "sqlite":
            return "1" if value else "0"
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (datetime, date, time)):
        return _literal(value.isoformat())
    return _literal(str(value))


def _literal(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _name(prefix: str, *parts: str) -> str:
    """Детерминированное имя констрейнта, обрезанное до предела Postgres."""
    name = "_".join([prefix, *parts])
    if len(name) <= MAX_IDENTIFIER:
        return name
    digest = hashlib.sha1(name.encode("utf-8")).hexdigest()[:8]
    shortened = f"{name[: MAX_IDENTIFIER - 9]}_{digest}"
    warnings.warn(
        f"constraint name {name!r} is longer than {MAX_IDENTIFIER} chars and was "
        f"shortened to {shortened!r}",
        stacklevel=3,
    )
    return shortened
