"""Deterministic typed-table generation and its command-line interface."""

from __future__ import annotations

import argparse
import importlib
import inspect
import keyword
import os
import sys
import types
from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import (
    Any,
    BinaryIO,
    ForwardRef,
    Literal,
    Protocol,
    TypeVar,
    cast,
    get_args,
    get_origin,
)

_tomllib = importlib.import_module("tomllib" if sys.version_info >= (3, 11) else "tomli")


class _TomlModule(Protocol):
    TOMLDecodeError: type[Exception]

    def load(self, stream: BinaryIO, /) -> dict[str, Any]: ...


tomllib = cast(_TomlModule, _tomllib)

GENERATED_HEADER = (
    "# Generated by pikanaut. DO NOT EDIT.\n# Regenerate with: pikanaut generate\n"
)


class GenerationError(Exception):
    """The project configuration or discovered table set cannot be generated."""


class GenerationStale(GenerationError):
    """Generated files are missing, stale, or unexpectedly present."""


@dataclass(frozen=True)
class _Config:
    project_root: Path
    models: tuple[str, ...]
    output_package: str
    source_roots: tuple[Path, ...]
    output_directory: Path


@dataclass(frozen=True)
class _TableSpec:
    model: type[Any]
    info: Any
    package: str | None
    prefix: str


class _Imports:
    """Assign stable, collision-free local names to imported runtime classes."""

    def __init__(self, refs: Iterable[type[Any]], reserved: set[str]) -> None:
        roots: dict[tuple[str, str], type[Any]] = {}
        for ref in refs:
            module = ref.__module__
            qualname = ref.__qualname__
            if "<locals>" in qualname:
                raise GenerationError(
                    f"cannot render local type {module}.{qualname}; declare it at module scope"
                )
            root_name = qualname.split(".", 1)[0]
            root = getattr(importlib.import_module(module), root_name, None)
            if not isinstance(root, type):
                raise GenerationError(
                    f"cannot import annotation type {module}.{qualname}"
                )
            roots[(module, root_name)] = root

        self._aliases: dict[tuple[str, str], str] = {}
        used = set(reserved)
        for module, name in sorted(roots):
            alias = name
            if alias in used:
                stem = f"_{name}"
                alias = stem
                suffix = 2
                while alias in used:
                    alias = f"{stem}_{suffix}"
                    suffix += 1
            used.add(alias)
            self._aliases[(module, name)] = alias

    def expression(self, ref: type[Any]) -> str:
        root, *suffix = ref.__qualname__.split(".")
        alias = self._aliases[(ref.__module__, root)]
        return ".".join((alias, *suffix))

    def lines(self) -> list[str]:
        result: list[str] = []
        for (module, name), alias in sorted(self._aliases.items()):
            suffix = "" if alias == name else f" as {alias}"
            result.append(f"from {module} import {name}{suffix}")
        return result


def _valid_dotted(value: object, label: str) -> str:
    if not isinstance(value, str) or not value:
        raise GenerationError(f"{label} must be a non-empty dotted Python name")
    parts = value.split(".")
    if any(not part.isidentifier() or keyword.iskeyword(part) for part in parts):
        raise GenerationError(f"{label} {value!r} is not a valid dotted Python name")
    return value


def _module_exists(root: Path, module: str) -> bool:
    path = root.joinpath(*module.split("."))
    return path.with_suffix(".py").is_file() or (path / "__init__.py").is_file()


def _inside(path: Path, parent: Path) -> bool:
    try:
        path.relative_to(parent)
    except ValueError:
        return False
    return True


def _load_config(
    config_path: str | os.PathLike[str], output_directory: str | os.PathLike[str] | None
) -> _Config:
    path = Path(config_path).expanduser().resolve()
    if not path.is_file():
        raise GenerationError(f"configuration file not found: {path}")
    try:
        with path.open("rb") as stream:
            document = tomllib.load(stream)
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise GenerationError(f"cannot read {path}: {exc}") from exc

    raw_tool = document.get("tool")
    if not isinstance(raw_tool, dict):
        raise GenerationError(f"{path}: missing [tool.pikanaut]")
    tool = cast(dict[str, object], raw_tool)
    raw_section = tool.get("pikanaut")
    if not isinstance(raw_section, dict):
        raise GenerationError(f"{path}: missing [tool.pikanaut]")
    section = cast(dict[str, object], raw_section)
    raw_models = section.get("models")
    if not isinstance(raw_models, list) or not raw_models:
        raise GenerationError("[tool.pikanaut].models must be a non-empty list")
    model_values = cast(list[object], raw_models)
    models = tuple(_valid_dotted(value, "model module") for value in model_values)
    if len(models) != len(set(models)):
        raise GenerationError("[tool.pikanaut].models contains duplicate modules")
    output_package = _valid_dotted(section.get("output_package"), "output_package")
    project_root = path.parent

    roots = (project_root, project_root / "src")
    source_roots: list[Path] = []
    for module in models:
        matches = [root for root in roots if _module_exists(root, module)]
        if not matches:
            raise GenerationError(
                f"model module {module!r} was not found in flat or src project layout"
            )
        if len(matches) > 1:
            raise GenerationError(
                f"model module {module!r} is ambiguous between {matches[0]} and {matches[1]}"
            )
        if matches[0] not in source_roots:
            source_roots.append(matches[0])

    explicit: str | os.PathLike[str] | None = output_directory
    if explicit is None:
        configured_output = section.get("output_directory")
        if configured_output is not None and not isinstance(configured_output, str):
            raise GenerationError("output_directory must be a filesystem path")
        explicit = configured_output
    if explicit is not None:
        raw_path = Path(explicit).expanduser()
        output = raw_path if raw_path.is_absolute() else project_root / raw_path
        output = output.resolve()
    else:
        top_package = output_package.split(".", 1)[0]
        candidates = [root for root in roots if (root / top_package).is_dir()]
        if len(candidates) > 1:
            raise GenerationError(
                "output package root is ambiguous between flat and src layouts; "
                "set output_directory explicitly"
            )
        if not candidates:
            # A new top-level package is safe only when all model modules use one layout.
            if len(source_roots) != 1:
                raise GenerationError(
                    "cannot infer output package root; set output_directory explicitly"
                )
            candidates = source_roots
        output = candidates[0].joinpath(*output_package.split(".")).resolve()

    if not _inside(output, project_root):
        raise GenerationError(
            "output_directory must remain inside the project directory"
        )
    return _Config(
        project_root=project_root,
        models=models,
        output_package=output_package,
        source_roots=tuple(source_roots),
        output_directory=output,
    )


def _purge_project_modules(config: _Config) -> None:
    """Import configured application modules afresh on every generation run."""

    prefixes = {name.split(".", 1)[0] for name in config.models}
    for name in tuple(sys.modules):
        if name.split(".", 1)[0] in prefixes:
            del sys.modules[name]


def _discover(config: _Config) -> list[_TableSpec]:
    from pikanaut.schema import TableModel, is_concrete_table, table_of

    table_lookup = cast(Callable[[type[object]], Any], table_of)

    old_path = sys.path[:]
    old_bytecode = sys.dont_write_bytecode
    sys.path[:0] = [str(path) for path in reversed(config.source_roots)]
    sys.dont_write_bytecode = True
    try:
        importlib.invalidate_caches()
        _purge_project_modules(config)
        modules = [importlib.import_module(name) for name in config.models]
    except Exception as exc:
        raise GenerationError(
            f"failed to import configured model module: {exc}"
        ) from exc
    finally:
        sys.path[:] = old_path
        sys.dont_write_bytecode = old_bytecode

    discovered: dict[int, type[Any]] = {}
    for module in modules:
        for value in vars(module).values():
            if (
                inspect.isclass(value)
                and value is not TableModel
                and issubclass(value, TableModel)
            ):
                discovered[id(value)] = value

    tables: list[_TableSpec] = []
    for model in discovered.values():
        if not is_concrete_table(model):
            continue
        try:
            info = table_lookup(model)
        except Exception as exc:
            raise GenerationError(
                f"invalid table model {model.__name__}: {exc}"
            ) from exc
        name = getattr(info, "name", None)
        schema = getattr(info, "schema", None)
        if not isinstance(name, str):
            raise GenerationError(
                f"{model.__name__}: table metadata has no string name"
            )
        _valid_export(name, f"table {model.__name__}")
        if schema is not None:
            _valid_export(schema, f"schema for table {name!r}")
        tables.append(
            _TableSpec(
                model=model,
                info=info,
                package=schema,
                prefix=_class_prefix(name),
            )
        )
    if not tables:
        raise GenerationError(
            "configured modules contain no concrete TableModel classes"
        )
    tables.sort(
        key=lambda item: (
            (item.package or ""),
            item.info.name,
            item.model.__module__,
            item.model.__qualname__,
        )
    )
    _validate_collisions(tables)
    return tables


def _valid_export(name: str, label: str) -> None:
    if not name.isidentifier() or keyword.iskeyword(name):
        raise GenerationError(
            f"{label} name {name!r} is not a valid Python identifier; names are not normalized"
        )


def _class_prefix(table_name: str) -> str:
    prefix = "".join(
        part[:1].upper() + part[1:] for part in table_name.split("_") if part
    )
    if not prefix or not prefix.isidentifier() or keyword.iskeyword(prefix):
        raise GenerationError(
            f"cannot derive a generated class name from table {table_name!r}"
        )
    return prefix


def _validate_collisions(tables: Sequence[_TableSpec]) -> None:
    exports: dict[str | None, dict[str, _TableSpec]] = {}
    classes: dict[str | None, dict[str, _TableSpec]] = {}
    schemas = {table.package for table in tables if table.package is not None}
    for table in tables:
        package_exports = exports.setdefault(table.package, {})
        previous = package_exports.get(table.info.name)
        if previous is not None:
            package = table.package or "<root>"
            raise GenerationError(
                f"duplicate generated export {table.info.name!r} in package {package!r}"
            )
        package_exports[table.info.name] = table
        generated_names = (
            f"{table.prefix}Source",
            f"{table.prefix}UpdateValues",
            f"{table.prefix}Update",
            f"{table.prefix}Table",
        )
        package_classes = classes.setdefault(table.package, {})
        for generated_name in generated_names:
            if generated_name in package_classes:
                raise GenerationError(
                    f"generated class name collision {generated_name!r} in schema package"
                )
            package_classes[generated_name] = table
    for root_name in exports.get(None, {}):
        if root_name in schemas:
            raise GenerationError(
                f"root table export {root_name!r} collides with schema package {root_name!r}"
            )


def _collect_refs(annotation: object, refs: set[type[Any]]) -> None:
    if annotation is Any or annotation is None or annotation is type(None):
        return
    if isinstance(annotation, (TypeVar, ForwardRef, str)):
        raise GenerationError(f"cannot render unresolved annotation {annotation!r}")
    origin = get_origin(annotation)
    if origin in (types.UnionType, getattr(__import__("typing"), "Union")):
        for arg in get_args(annotation):
            _collect_refs(arg, refs)
        return
    if origin is Literal:
        for value in get_args(annotation):
            if isinstance(value, type):
                refs.add(value)
            elif (
                hasattr(value, "__class__") and value.__class__.__module__ != "builtins"
            ):
                refs.add(value.__class__)
        return
    if origin is not None:
        if inspect.isclass(origin) and origin.__module__ != "builtins":
            refs.add(origin)
        for arg in get_args(annotation):
            if arg is not Ellipsis:
                _collect_refs(arg, refs)
        return
    if inspect.isclass(annotation):
        if annotation.__module__ != "builtins":
            refs.add(annotation)
        return
    raise GenerationError(f"cannot render annotation {annotation!r}")


def _render_annotation(annotation: object, imports: _Imports) -> str:
    if annotation is Any:
        return "Any"
    if annotation is None or annotation is type(None):
        return "None"
    if isinstance(annotation, (TypeVar, ForwardRef, str)):
        raise GenerationError(f"cannot render unresolved annotation {annotation!r}")
    origin = get_origin(annotation)
    union_origin = getattr(__import__("typing"), "Union")
    if origin in (types.UnionType, union_origin):
        return " | ".join(
            _render_annotation(arg, imports) for arg in get_args(annotation)
        )
    if origin is Literal:
        values: list[str] = []
        for value in get_args(annotation):
            if hasattr(value, "__class__") and value.__class__.__module__ != "builtins":
                values.append(f"{imports.expression(value.__class__)}.{value.name}")
            else:
                values.append(repr(value))
        return f"Literal[{', '.join(values)}]"
    if origin is not None:
        if inspect.isclass(origin):
            base = (
                origin.__name__
                if origin.__module__ == "builtins"
                else imports.expression(origin)
            )
        else:
            raise GenerationError(f"cannot render generic annotation {annotation!r}")
        arguments = [
            "..." if arg is Ellipsis else _render_annotation(arg, imports)
            for arg in get_args(annotation)
        ]
        return f"{base}[{', '.join(arguments)}]"
    if inspect.isclass(annotation):
        return (
            annotation.__name__
            if annotation.__module__ == "builtins"
            else imports.expression(annotation)
        )
    raise GenerationError(f"cannot render annotation {annotation!r}")


def _without_none(annotation: object) -> object:
    args = get_args(annotation)
    origin = get_origin(annotation)
    union_origin = getattr(__import__("typing"), "Union")
    if origin not in (types.UnionType, union_origin):
        return annotation
    kept = tuple(arg for arg in args if arg is not type(None))
    if len(kept) == 1:
        return kept[0]
    result = kept[0]
    for item in kept[1:]:
        result = result | item
    return result


def _is_always_identity(field: Any) -> bool:
    default = getattr(field, "server_default", None)
    return (
        default is not None
        and type(default).__name__ == "Identity"
        and getattr(default, "generated", None) == "ALWAYS"
    )


def _annotation_uses(annotation: object, expected: object) -> bool:
    if annotation is expected:
        return True
    return any(_annotation_uses(argument, expected) for argument in get_args(annotation))


def _uses_literal(annotation: object) -> bool:
    if get_origin(annotation) is Literal:
        return True
    return any(_uses_literal(argument) for argument in get_args(annotation))


def _module_text(tables: Sequence[_TableSpec]) -> str:
    refs: set[type[Any]] = {table.model for table in tables}
    for table in tables:
        for field in table.info.fields:
            _collect_refs(field.annotation, refs)
    reserved = {
        "Any",
        "Dialect",
        "Limits",
        "Self",
        "TypedDict",
        "Unpack",
        "Column",
        "Table",
        "Update",
    }
    imports = _Imports(refs, reserved)
    typing_names = ["TypedDict"]
    if any(
        _annotation_uses(field.annotation, Any)
        for table in tables
        for field in table.info.fields
    ):
        typing_names.insert(0, "Any")
    if any(_uses_literal(field.annotation) for table in tables for field in table.info.fields):
        typing_names.insert(0, "Literal")
    lines = [
        GENERATED_HEADER.rstrip("\n"),
        "",
        "from __future__ import annotations",
        "",
        f"from typing import {', '.join(typing_names)}",
        "from typing_extensions import Self, Unpack",
        "",
        "from pikanaut.client import Update",
        "from pikanaut.dialects.base import Dialect, Limits",
        "from pikanaut.expr import Column",
        "from pikanaut.tables import Table",
    ]
    import_lines = imports.lines()
    if import_lines:
        lines.extend(("", *import_lines))

    exported: list[str] = []
    for table in tables:
        source = f"{table.prefix}Source"
        update_values = f"{table.prefix}UpdateValues"
        update = f"{table.prefix}Update"
        table_class = f"{table.prefix}Table"
        model_name = imports.expression(table.model)
        exported.extend((source, update_values, update, table_class, table.info.name))
        lines.extend(("", "", f"class {source}:", "    pass"))
        lines.extend(("", "", f"class {update_values}(TypedDict, total=False):"))
        writable = [
            field for field in table.info.fields if not _is_always_identity(field)
        ]
        if not writable:
            lines.append("    pass")
        for field in writable:
            value = _render_annotation(field.annotation, imports)
            base = _render_annotation(_without_none(field.annotation), imports)
            column_types = [f"Column[{value}, {source}]"]
            if getattr(field, "nullable", False) and base != value:
                column_types.insert(0, f"Column[{base}, {source}]")
            lines.append(f"    {field.name}: {value} | {' | '.join(column_types)}")
        lines.extend(
            (
                "",
                "",
                f"class {update}(Update[{source}]):",
                f"    def set(self, **values: Unpack[{update_values}]) -> Self:",
                "        return self._set_values(values)",
                "",
                "",
                f"class {table_class}(Table[{model_name}, {source}]):",
            )
        )
        for field in table.info.fields:
            annotation = _render_annotation(field.annotation, imports)
            lines.append(f"    {field.name}: Column[{annotation}, {source}]")
        lines.extend(
            (
                "",
                "    def __init__(self) -> None:",
                f"        super().__init__({model_name})",
            )
        )
        for field in table.info.fields:
            lines.append(
                f"        self.{field.name} = self.__pikanaut_column__({field.name!r})"
            )
        lines.extend(
            (
                "",
                "    def __pikanaut_update__(",
                "        self, dialect: Dialect, limits: Limits, require_where: bool = True",
                f"    ) -> {update}:",
                f"        return {update}(",
                "            dialect, limits, self.__pikanaut_info__, require_where=require_where",
                "        )",
                "",
                "",
                f"{table.info.name} = {table_class}()",
            )
        )
    lines.extend(("", "", f"__all__ = {exported!r}", ""))
    return "\n".join(lines)


def _expected_files(config: _Config, tables: Sequence[_TableSpec]) -> dict[Path, bytes]:
    grouped: dict[str | None, list[_TableSpec]] = {}
    for table in tables:
        grouped.setdefault(table.package, []).append(table)
    result: dict[Path, bytes] = {}
    # The root package is emitted even when all tables are schema-qualified.
    for package in sorted(grouped, key=lambda value: value or ""):
        directory = (
            config.output_directory
            if package is None
            else config.output_directory / package
        )
        result[directory / "__init__.py"] = _module_text(grouped[package]).encode(
            "utf-8"
        )
    if None not in grouped:
        schemas = sorted(package for package in grouped if package is not None)
        text = GENERATED_HEADER + "\n" + f"__all__ = {schemas!r}\n"
        result[config.output_directory / "__init__.py"] = text.encode("utf-8")
    return result


def _owned_files(output: Path) -> set[Path]:
    if not output.exists():
        return set()
    if not output.is_dir():
        raise GenerationError(f"output path is not a directory: {output}")
    owned: set[Path] = set()
    header = GENERATED_HEADER.encode("utf-8")
    for path in output.rglob("*.py"):
        if path.is_file():
            try:
                if path.read_bytes().startswith(header):
                    owned.add(path)
            except OSError as exc:
                raise GenerationError(
                    f"cannot inspect generated file {path}: {exc}"
                ) from exc
    return owned


def _differences(expected: dict[Path, bytes], owned: set[Path]) -> list[str]:
    differences: list[str] = []
    for path, content in expected.items():
        if not path.exists():
            differences.append(f"missing: {path}")
            continue
        if not path.is_file():
            differences.append(f"not a file: {path}")
            continue
        existing = path.read_bytes()
        if not existing.startswith(GENERATED_HEADER.encode("utf-8")):
            raise GenerationError(f"refusing to overwrite user-owned file: {path}")
        if existing != content:
            differences.append(f"stale: {path}")
    for path in sorted(owned - set(expected)):
        differences.append(f"stale generated file: {path}")
    return differences


def generate(
    config_path: str | os.PathLike[str] = "pyproject.toml",
    *,
    check: bool = False,
    output_directory: str | os.PathLike[str] | None = None,
) -> tuple[Path, ...]:
    """Generate configured typed tables, or verify them without writing."""

    config = _load_config(config_path, output_directory)
    tables = _discover(config)
    expected = _expected_files(config, tables)
    owned = _owned_files(config.output_directory)
    differences = _differences(expected, owned)
    if check:
        if differences:
            raise GenerationStale(
                "generated tables are not current:\n" + "\n".join(differences)
            )
        return tuple(sorted(expected))

    for path, content in sorted(expected.items()):
        if path.exists() and path.read_bytes() == content:
            continue
        if path.exists() and not path.read_bytes().startswith(
            GENERATED_HEADER.encode("utf-8")
        ):
            raise GenerationError(f"refusing to overwrite user-owned file: {path}")
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(f".{path.name}.pikanaut.tmp")
        temporary.write_bytes(content)
        temporary.replace(path)
    for path in sorted(owned - set(expected), reverse=True):
        path.unlink()
    if config.output_directory.exists():
        directories = sorted(
            (path for path in config.output_directory.rglob("*") if path.is_dir()),
            key=lambda path: len(path.parts),
            reverse=True,
        )
        for directory in directories:
            try:
                directory.rmdir()
            except OSError:
                pass
    return tuple(sorted(expected))


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="pikanaut")
    subcommands = parser.add_subparsers(dest="command", required=True)
    generate_parser = subcommands.add_parser(
        "generate", help="generate typed table modules"
    )
    generate_parser.add_argument(
        "--check", action="store_true", help="fail if output is missing or stale"
    )
    generate_parser.add_argument(
        "--config", default="pyproject.toml", help="path to application pyproject.toml"
    )
    generate_parser.add_argument(
        "--output-directory",
        help="explicit generated package directory, relative to the project root",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    if args.command != "generate":  # pragma: no cover - argparse enforces this
        return 2
    try:
        paths = generate(
            args.config,
            check=bool(args.check),
            output_directory=args.output_directory,
        )
    except GenerationError as exc:
        print(f"pikanaut: {exc}", file=sys.stderr)
        return 1
    action = "checked" if args.check else "generated"
    print(f"{action} {len(paths)} file(s)")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
