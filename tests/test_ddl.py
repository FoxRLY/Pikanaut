"""DDL: CREATE TABLE / CREATE INDEX / DROP TABLE из модели.

Контракт — точный текст (golden), плюс отдельная проверка, что sqlite принимает
сгенерированную схему и что она ведёт себя как задумано (identity, unique, index).
"""

from __future__ import annotations

import sqlite3
from datetime import datetime
from decimal import Decimal
from typing import Annotated

import pytest
from pydantic import BaseModel

from pikanaut import Col, SchemaError, UnsupportedFeature, ddl, table
from pikanaut.dialects import POSTGRES, SQLITE


@table("notes")
class Note(BaseModel):
    id: Annotated[int | None, Col(pk=True)] = None
    text: str
    created_at: Annotated[datetime, Col(default=ddl.NOW)]


@table("users")
class User(BaseModel):
    id: Annotated[int, Col(pk=True)]
    email: Annotated[str, Col(unique=True)]
    tenant: Annotated[str, Col(index=True)]
    amount: Decimal
    meta: dict[str, int]
    age: int | None = None


@table("users", schema="public")
class PublicUser(BaseModel):
    id: Annotated[int, Col(pk=True)]
    email: str


@table("flags")
class Flag(BaseModel):
    id: Annotated[int | None, Col(pk=True)] = None
    is_active: Annotated[bool, Col(default=True)]
    label: Annotated[str | None, Col(default='none')]


@table("q")
class Quoted(BaseModel):
    id: Annotated[int, Col(pk=True)]
    text: Annotated[str, Col(default="it's")]


@table("weird")
class Weird(BaseModel):
    id: Annotated[int, Col(pk=True)]
    payload: complex                      # pydantic умеет complex, SQL-типа у нас для него нет


@table("t" * 60)
class Long(BaseModel):
    id: Annotated[int, Col(pk=True)]
    email: Annotated[str, Col(unique=True)]


def index_of(statements, column: str):
    for statement in statements:
        if f'("{column}")' in statement.sql:
            return statement
    return None


def test_sqlite_table_with_rowid_identity() -> None:
    statements = ddl.create(Note, dialect=SQLITE)
    assert [s.sql for s in statements] == [
        'CREATE TABLE IF NOT EXISTS "notes" ("id" INTEGER PRIMARY KEY,'
        '"text" TEXT NOT NULL,"created_at" TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP)'
    ]
    assert statements[0].params == []


def test_postgres_table_with_identity_and_pk_name() -> None:
    (statement,) = ddl.create(Note, dialect=POSTGRES)
    assert statement.sql == (
        'CREATE TABLE IF NOT EXISTS "notes" ('
        '"id" INTEGER GENERATED BY DEFAULT AS IDENTITY,'
        '"text" TEXT NOT NULL,'
        '"created_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,'
        'CONSTRAINT "pk_notes" PRIMARY KEY ("id"))'
    )


def test_sqlite_types_and_constraints() -> None:
    statements = ddl.create(User, dialect=SQLITE)
    assert statements[0].sql == (
        'CREATE TABLE IF NOT EXISTS "users" ('
        '"id" INTEGER NOT NULL,'
        '"email" TEXT NOT NULL,'
        '"tenant" TEXT NOT NULL,'
        '"amount" TEXT NOT NULL,'
        '"meta" TEXT NOT NULL,'
        '"age" INTEGER,'
        'CONSTRAINT "pk_users" PRIMARY KEY ("id"),'
        'CONSTRAINT "uq_users_email" UNIQUE ("email"))'
    )
    assert [s.sql for s in statements[1:]] == [
        'CREATE INDEX IF NOT EXISTS "ix_users_tenant" ON "users" ("tenant")'
    ]


def test_postgres_types_schema_and_index() -> None:
    statements = ddl.create(PublicUser, dialect=POSTGRES)
    assert statements[0].sql == (
        'CREATE TABLE IF NOT EXISTS "public"."users" ('
        '"id" INTEGER NOT NULL,"email" TEXT NOT NULL,'
        'CONSTRAINT "pk_users" PRIMARY KEY ("id"))'
    )

    table_statement, *indexes = ddl.create(User, dialect=POSTGRES)
    assert '"amount" NUMERIC NOT NULL' in table_statement.sql
    assert '"meta" JSONB NOT NULL' in table_statement.sql
    assert index_of(indexes, "tenant") is not None


def test_defaults_only_from_col() -> None:
    (statement,) = ddl.create(Flag, dialect=SQLITE)
    assert statement.sql == (
        'CREATE TABLE IF NOT EXISTS "flags" ("id" INTEGER PRIMARY KEY,'
        '"is_active" INTEGER NOT NULL DEFAULT 1,'
        "\"label\" TEXT DEFAULT 'none')"
    )


def test_string_default_is_escaped() -> None:
    (statement,) = ddl.create(Quoted, dialect=SQLITE)
    assert "DEFAULT 'it''s'" in statement.sql


def test_unknown_type_requires_explicit_sql_type() -> None:
    with pytest.raises(SchemaError, match=r"Col\(type"):
        ddl.create(Weird, dialect=SQLITE)


def test_schema_unsupported_on_sqlite() -> None:
    with pytest.raises(UnsupportedFeature, match="schema"):
        ddl.create(PublicUser, dialect=SQLITE)


def test_drop() -> None:
    assert ddl.drop(Note, dialect=SQLITE).sql == 'DROP TABLE IF EXISTS "notes"'
    assert ddl.drop(PublicUser, dialect=POSTGRES).sql == 'DROP TABLE IF EXISTS "public"."users"'


def test_long_names_are_truncated_to_63() -> None:
    (statement,) = ddl.create(Long, dialect=POSTGRES)
    fragments = statement.sql.split("CONSTRAINT ")[1:]
    assert fragments, "констрейнты должны быть именованы"
    for fragment in fragments:
        name = fragment.split()[0].strip('"')
        assert len(name) <= 63, name


def test_sqlite_accepts_generated_schema() -> None:
    conn = sqlite3.connect(":memory:")
    for statement in ddl.create(Note, dialect=SQLITE):
        conn.execute(statement.sql)
    conn.execute('INSERT INTO notes ("text") VALUES (?)', ("x",))
    row = conn.execute('SELECT "id","text","created_at" FROM "notes"').fetchone()
    assert row[0] == 1 and row[1] == "x" and row[2] is not None


def test_sqlite_rowid_identity_autoincrements() -> None:
    conn = sqlite3.connect(":memory:")
    for statement in ddl.create(Note, dialect=SQLITE):
        conn.execute(statement.sql)
    ids = []
    for text in ("a", "b"):
        cursor = conn.execute('INSERT INTO notes ("text") VALUES (?)', (text,))
        ids.append(cursor.lastrowid)
    assert ids == [1, 2]


def test_sqlite_enforces_unique_and_exposes_index() -> None:
    conn = sqlite3.connect(":memory:")
    for statement in ddl.create(User, dialect=SQLITE):
        conn.execute(statement.sql)

    values = (1, "a@b.io", "t1", "10.50", "{}")
    conn.execute(
        'INSERT INTO users ("id","email","tenant","amount","meta") VALUES (?,?,?,?,?)', values
    )
    with pytest.raises(sqlite3.IntegrityError):
        conn.execute(
            'INSERT INTO users ("id","email","tenant","amount","meta") VALUES (?,?,?,?,?)',
            (2, "a@b.io", "t2", "1.00", "{}"),
        )

    names = {row[1] for row in conn.execute("PRAGMA index_list('users')")}
    assert "ix_users_tenant" in names


def test_decimal_kept_as_text_on_sqlite() -> None:
    conn = sqlite3.connect(":memory:")
    for statement in ddl.create(User, dialect=SQLITE):
        conn.execute(statement.sql)
    conn.execute(
        'INSERT INTO users ("id","email","tenant","amount","meta") VALUES (?,?,?,?,?)',
        (1, "a@b.io", "t", "10.50", "{}"),
    )
    value, kind = conn.execute('SELECT "amount", typeof("amount") FROM users').fetchone()
    assert (value, kind) == ("10.50", "text")


def test_repeated_create_is_idempotent() -> None:
    conn = sqlite3.connect(":memory:")
    for _ in range(2):
        for statement in ddl.create(Note, dialect=SQLITE):
            conn.execute(statement.sql)
